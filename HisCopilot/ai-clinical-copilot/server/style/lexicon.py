def is_known_herb(name: str) -> bool:
    n = clean_name(name)
    return any(b in HERBS or _EXTRA_ALIASES.get(b, "") in HERBS for b in base_names(n))


def canonical(name: str) -> str:
    """炙黄芪 → 黄芪（保留原名供展示，统计用规范名）；别名并入主名。"""
    n = clean_name(name)
    for b in sorted(base_names(n), key=len):         # shortest known base first: 炙黄芪→黄芪，生石膏→石膏
        if b in HERBS or b in _EXTRA_ALIASES:
            return _EXTRA_ALIASES.get(b, b)
    return n


def longest_herb_at(text: str, i: int) -> str:
    """text[i:] 开头最长的已知药名（含炙/制/生等炮制前缀），没有则 ""。"""
    for ln in range(min(_MAXLEN + 2, len(text) - i), 1, -1):
        cand = text[i:i + ln]
        if is_known_herb(cand) and clean_name(cand) == cand:
            return cand
    return ""


def special_in(s: str) -> str:
    m = _SPECIAL_RE.search(s or "")
    return m.group(0) if m else ""


