def _build() -> tuple[set[str], int]:
    names: set[str] = set(_EXTRA)
    for n, _lo, _hi, _sp, aliases in R.HERBS:
        names.add(n)
        names.update(aliases)
    names |= R.TOXIC_HERBS | R.PREGNANCY_FORBIDDEN | R.PREGNANCY_CAUTION
    names = {n for n in names if 1 < len(n) <= 6}
    return names, max(len(n) for n in names)


